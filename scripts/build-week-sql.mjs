// Turn a reviewed week draft (docs/content-rebuild/week-NN-*.html) into the SQL
// that loads it into `entries`. The review HTML John marks up is the source of
// truth for the words; this keeps the database copy from drifting from it.
//
//   node scripts/build-week-sql.mjs docs/content-rebuild/week-01-*.html [more.html ...] > out.sql
//
// Per day it sets: title, body_text (the reading, *emphasis* kept as asterisks),
// carry_line, with_dad_prompt, with_dad_minutes, share_prompt, recap_line (from
// the email page). It clears reflection_prompt (the old check-in prompt) and
// audio_url (the old recording no longer matches the new words; the new audio
// is uploaded with `npm run upload:audio` once John records it).
// It only WRITES SQL. Apply it with scripts/db-exec.mjs when it's time to go live.
import { readFileSync } from 'node:fs'

// --only=1,2 limits the output to those days (e.g. to go live a day at a time
// as the recordings come in).
const onlyArg = process.argv.find((a) => a.startsWith('--only='))
const only = onlyArg ? new Set(onlyArg.slice('--only='.length).split(',').map(Number)) : null
const files = process.argv.slice(2).filter((a) => !a.startsWith('--'))
if (!files.length) {
  console.error('Usage: node scripts/build-week-sql.mjs <week-html> [...] [--only=1,2] > out.sql')
  process.exit(1)
}

const decode = (s) => s
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&rsaquo;/g, '›').replace(/&quot;/g, '"')
  .replace(/&#39;/g, "'").replace(/&amp;/g, '&')

// <em>x</em> -> *x*; drop every other tag; collapse whitespace.
const toText = (html) => decode(html
  .replace(/<em>([\s\S]*?)<\/em>/g, '*$1*')
  .replace(/<[^>]+>/g, '')
  .replace(/\s+/g, ' ')
  .trim())

const paragraphs = (html) => [...html.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)].map((m) => toText(m[1])).filter(Boolean)

// The block of a labelled .section (Reading, With Dad, Share).
function section(dayHtml, label) {
  const re = new RegExp(`<div class="label">${label}[\\s\\S]*?</div>([\\s\\S]*?)(?=<div class="section">|<div class="notes">|<div class="carry">|</section>)`)
  const m = dayHtml.match(re)
  return m ? m[1] : ''
}

const days = []
const recaps = new Map()

for (const file of files) {
  const html = readFileSync(file, 'utf8')

  for (const m of html.matchAll(/<p><b>Day (\d+), [\s\S]*?<\/b>([\s\S]*?)<span class="link">/g)) {
    recaps.set(Number(m[1]), toText(m[2]))
  }

  for (const m of html.matchAll(/<section class="day">([\s\S]*?)<\/section>/g)) {
    const d = m[1]
    const sortIndex = Number(d.match(/<span class="kicker">Day (\d+) ·/)?.[1])
    const title = toText(d.match(/<h2>([\s\S]*?)<\/h2>/)?.[1] ?? '')
    const reading = paragraphs(section(d, 'Reading')).join('\n\n')
    const carry = toText(d.match(/<div class="handle">([\s\S]*?)<\/div>/)?.[1] ?? '')
    const withDadBlock = section(d, 'With Dad')
    const minutes = Number(d.match(/<div class="label">With Dad <span class="meta">(\d+) minute/)?.[1]) || null
    const withDad = paragraphs(withDadBlock).join(' ')
    const share = paragraphs(section(d, 'Share')).join(' ')
    if (!sortIndex || !title || !reading) throw new Error(`${file}: could not parse a day (got sortIndex=${sortIndex}, title=${title})`)
    if (only && !only.has(sortIndex)) continue
    days.push({ sortIndex, title, reading, carry, withDad, minutes, share })
  }
}

days.sort((a, b) => a.sortIndex - b.sortIndex)
for (const d of days) {
  if (!recaps.has(d.sortIndex)) throw new Error(`No email recap line for day ${d.sortIndex}`)
  for (const k of ['carry', 'withDad', 'minutes', 'share']) if (!d[k]) throw new Error(`Day ${d.sortIndex}: missing ${k}`)
}

// Dollar-quoted so apostrophes and quotes in the copy need no escaping.
const q = (s) => {
  if (s.includes('$c$')) throw new Error('copy contains the dollar-quote tag')
  return `$c$${s}$c$`
}

const rows = days.map((d) => `  (${d.sortIndex}, ${q(d.title)}, ${q(d.reading)}, ${q(d.carry)}, ${q(d.withDad)}, ${d.minutes}, ${q(d.share)}, ${q(recaps.get(d.sortIndex))})`)

process.stdout.write(`-- GENERATED by scripts/build-week-sql.mjs from ${files.map((f) => f.replace(/\\/g, '/').split('/').pop()).join(', ')}.
-- Do not hand-edit: change the review HTML and regenerate.
-- Loads the rebuilt content for days ${days[0].sortIndex}-${days.at(-1).sortIndex}. Days that don't exist yet are
-- created (ids follow the seed's e1000001-...-<sort_index> pattern). Clears the
-- old check-in prompt and the old audio pointer (old recordings don't match).
begin;

create temp table week_content (
  sort_index int, title text, body_text text, carry_line text, with_dad_prompt text,
  with_dad_minutes int, share_prompt text, recap_line text
) on commit drop;

insert into week_content values
${rows.join(',\n')};

insert into public.entries (id, week, day, sort_index, title, body_text)
select ('e1000001-0001-0001-0001-' || lpad(v.sort_index::text, 12, '0'))::uuid,
       (v.sort_index + 6) / 7, ((v.sort_index - 1) % 7) + 1, v.sort_index, v.title, v.body_text
from week_content v
where not exists (select 1 from public.entries e where e.sort_index = v.sort_index);

update public.entries e set
  title             = v.title,
  body_text         = v.body_text,
  carry_line        = v.carry_line,
  with_dad_prompt   = v.with_dad_prompt,
  with_dad_minutes  = v.with_dad_minutes,
  share_prompt      = v.share_prompt,
  recap_line        = v.recap_line,
  reflection_prompt = null,
  audio_url         = null
from week_content v
where e.sort_index = v.sort_index;

commit;
`)
